// Emits an Nginx snippet with security headers, including a strict CSP that
// allows exactly the inline scripts present in build/index.html (by hash).
//   node scripts/csp.mjs build > security-headers.conf
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2] ?? 'build';
const html = readFileSync(join(dir, 'index.html'), 'utf8');
const hashes = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(
  (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`
);

const csp = [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(' ')}`,
  // style-src-attr: SvelteKit's wrapper <div style="display: contents">.
  "style-src 'self'",
  "style-src-attr 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'"
].join('; ');

const h = (name, value) => `add_header ${name} "${value}" always;`;
console.log(
  [
    '# Generated by services/web/scripts/csp.mjs at image build time.',
    h('Content-Security-Policy', csp),
    h('X-Content-Type-Options', 'nosniff'),
    h('Referrer-Policy', 'strict-origin-when-cross-origin'),
    h('Permissions-Policy', 'camera=(), microphone=(), geolocation=(), interest-cohort=()'),
    h('Cross-Origin-Opener-Policy', 'same-origin')
  ].join('\n')
);
